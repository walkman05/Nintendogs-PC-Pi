#ifndef LOADER_H
#define LOADER_H

/* One compiled function and the DS location its name stands for (module -1 main, -2 ITCM, N overlay N). */
typedef struct {
    int module;
    unsigned int ds_addr;
    void (*fn)(void);
} HostFunc;

extern const HostFunc host_functab[];   /* generated by port/tools/gen_functab.py, sorted by module, address */
extern const int host_functab_count;

/* Loads the main program, ITCM and DTCM images from <dir> (the extracted/ folder) into the mapped DS memory,
 * clears their uninitialised data and rewrites function pointers in their data. Returns 0 on success. */
int ndogs_load_main(const char *dir);

/* FS_LoadOverlay on the host: copy overlay <id>, clear its bss, fix up pointers, run its constructors.
 * Returns 1 on success, 0 on failure (as the SDK function). */
int ndogs_load_overlay(int id);
int ndogs_unload_overlay(int id);

/* Host function for a DS code address in <module>, or 0 when none is known. */
void (*ndogs_host_func(int module, unsigned int ds_addr))(void);

#endif
