"""Generate the host function table: every decompiled / host function with the DS module and address its name
encodes (func_02001234 -> main 0x02001234, func_ov003_0215c000 -> ov003, func_01ff8000 -> itcm), so the loader can
turn DS code addresses found in game data into the compiled C functions. ROM-independent (names only).

usage: python port/tools/gen_functab.py <out.c>
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DEF = re.compile(r'^[A-Za-z_][\w \*]*?\b(func_(?:ov(\d{3})_)?([0-9a-f]{8}))\s*\([^;{]*\)\s*\{', re.M)


def main():
    names = {}
    for base in ('src', os.path.join('port', 'hostfuncs')):
        for dirpath, _, files in os.walk(os.path.join(ROOT, base)):
            for fn in files:
                if fn.endswith('.c'):
                    text = open(os.path.join(dirpath, fn), encoding='utf-8', errors='replace').read()
                    for m in DEF.finditer(text):
                        line_start = text.rfind('\n', 0, m.start()) + 1
                        if text[line_start:m.start(1)].lstrip().startswith('static'):
                            continue
                        name, ov, addr = m.group(1), m.group(2), int(m.group(3), 16)
                        mod = int(ov) if ov is not None else (-2 if 0x01ff8000 <= addr < 0x02000000 else -1)
                        names[name] = (mod, addr)
    # linker trampolines (port/link/veneers.txt) are real symbols too (x86 jump stubs), and data refers to them
    for line in open(os.path.join(ROOT, 'port', 'link', 'veneers.txt')):
        m = re.match(r'(func_(?:ov(\d{3})_)?([0-9a-f]{8}))\s*=', line)
        if m and m.group(1) not in names:
            addr = int(m.group(3), 16)
            names[m.group(1)] = (int(m.group(2)) if m.group(2) else (-2 if 0x01ff8000 <= addr < 0x02000000 else -1), addr)
    rows = sorted(names.items(), key=lambda kv: (kv[1][0], kv[1][1]))
    with open(sys.argv[1], 'w') as f:
        f.write('/* generated by port/tools/gen_functab.py */\n#include "loader.h"\n\n')
        for name, _ in rows:
            f.write('extern void %s(void);\n' % name)
        f.write('\nconst HostFunc host_functab[] = {\n')
        for name, (mod, addr) in rows:
            f.write('    { %d, 0x%08xu, %s },\n' % (mod, addr, name))
        f.write('};\nconst int host_functab_count = %d;\n' % len(rows))
    print('%d functions' % len(rows))


if __name__ == '__main__':
    main()
